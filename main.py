"""
FastAPI application for Text Summarization using Hugging Face model.
Model: facebook/bart-large-cnn
"""

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, field_validator
from transformers import AutoTokenizer, AutoModelForSeq2SeqLM
import torch
import time

# ── App initialization ────────────────────────────────────────────────────────
app = FastAPI(
    title="Text Summarization API",
    description="A Web API that uses the facebook/bart-large-cnn model from Hugging Face "
                "to summarize long texts into concise summaries.",
    version="1.0.0",
)

# ── Load model once at startup ────────────────────────────────────────────────
MODEL_NAME = "facebook/bart-large-cnn"
_tokenizer: AutoTokenizer = None
_model: AutoModelForSeq2SeqLM = None


@app.on_event("startup")
async def load_model():
    global _tokenizer, _model
    print(f"Loading model: {MODEL_NAME} …")
    _tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
    _model = AutoModelForSeq2SeqLM.from_pretrained(MODEL_NAME)
    _model.eval()
    print("Model loaded successfully.")


def _summarize(text: str, max_length: int, min_length: int) -> str:
    """Run BART summarization and return the summary string."""
    inputs = _tokenizer(
        text,
        return_tensors="pt",
        max_length=1024,
        truncation=True,
    )
    with torch.no_grad():
        summary_ids = _model.generate(
            inputs["input_ids"],
            max_length=max_length,
            min_length=min_length,
            length_penalty=2.0,
            num_beams=4,
            early_stopping=True,
        )
    return _tokenizer.decode(summary_ids[0], skip_special_tokens=True)


# ── Schemas ───────────────────────────────────────────────────────────────────
class SummarizeRequest(BaseModel):
    text: str
    max_length: int = 130
    min_length: int = 30

    @field_validator("text")
    @classmethod
    def text_must_not_be_empty(cls, v: str) -> str:
        v = v.strip()
        if not v:
            raise ValueError("'text' must not be empty.")
        if len(v.split()) < 10:
            raise ValueError(
                "'text' is too short to summarize (need at least 10 words)."
            )
        return v

    @field_validator("max_length")
    @classmethod
    def max_length_must_be_positive(cls, v: int) -> int:
        if v < 10:
            raise ValueError("'max_length' must be at least 10.")
        return v

    @field_validator("min_length")
    @classmethod
    def min_length_must_be_positive(cls, v: int) -> int:
        if v < 5:
            raise ValueError("'min_length' must be at least 5.")
        return v


class SummarizeResponse(BaseModel):
    model: str
    summary: str
    input_word_count: int
    summary_word_count: int
    processing_time_seconds: float


# ── Endpoints ─────────────────────────────────────────────────────────────────
@app.get("/", summary="API Introduction")
def root():
    """Returns a brief introduction to the API."""
    return {
        "api": "Text Summarization API",
        "model": MODEL_NAME,
        "model_url": f"https://huggingface.co/{MODEL_NAME}",
        "description": (
            "Submit a long piece of text and receive a concise summary "
            "generated by the BART large CNN model fine-tuned on CNN/DailyMail."
        ),
        "endpoints": {
            "GET  /": "API introduction (this page)",
            "GET  /health": "Health check",
            "POST /predict": "Summarize text",
        },
    }


@app.get("/health", summary="Health Check")
def health():
    """Checks whether the model is loaded and the service is operational."""
    if _model is None or _tokenizer is None:
        raise HTTPException(
            status_code=503,
            detail="Model is not loaded yet. Please try again in a moment.",
        )
    return {"status": "ok", "model_loaded": True, "model": MODEL_NAME}


@app.post("/predict", response_model=SummarizeResponse, summary="Summarize Text")
def predict(request: SummarizeRequest):
    """
    Receives a piece of text and returns its summary.

    - **text**: The input text to summarize (at least 10 words).
    - **max_length**: Maximum number of tokens in the summary (default: 130).
    - **min_length**: Minimum number of tokens in the summary (default: 30).
    """
    if _model is None or _tokenizer is None:
        raise HTTPException(
            status_code=503,
            detail="Model is not loaded yet. Please try again in a moment.",
        )

    if request.min_length >= request.max_length:
        raise HTTPException(
            status_code=422,
            detail="'min_length' must be strictly less than 'max_length'.",
        )

    try:
        start = time.perf_counter()
        summary_text = _summarize(request.text, request.max_length, request.min_length)
        elapsed = round(time.perf_counter() - start, 3)
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Model inference failed: {str(exc)}",
        )

    return SummarizeResponse(
        model=MODEL_NAME,
        summary=summary_text,
        input_word_count=len(request.text.split()),
        summary_word_count=len(summary_text.split()),
        processing_time_seconds=elapsed,
    )

